/** Display label for an ingredient in the given language. */
export function ingredientLabel(name: string, lang: string): string {
  return lang === 'tr' ? INGREDIENT_TR[name] ?? name : name;
}

export function searchIngredients(query: string, limit = 30): string[] {
  const q = query.trim().toLowerCase();
  const qTr = query.trim().toLocaleLowerCase('tr-TR');
  if (!q) return [];
  const starts: string[] = [];
  const contains: string[] = [];
  for (const name of ALL_INGREDIENTS) {
    const lower = name.toLowerCase();
    const trLower = (INGREDIENT_TR[name] ?? '').toLocaleLowerCase('tr-TR');
    if (lower.startsWith(q) || trLower.startsWith(qTr)) starts.push(name);
    else if (lower.includes(q) || (trLower && trLower.includes(qTr))) contains.push(name);
  }
  return [...starts, ...contains].slice(0, limit);
}
